/** The report language for a content language: Ukrainian for uk, English otherwise. */
export const reportLang = (language) => (String(language || "").toLowerCase().startsWith("uk") ? "uk" : "en");

/** Plural form for a count: forms are [one, few, many]; English uses one/many. */
export function plural(n, forms, lang) {
  if (lang === "en") return n === 1 ? forms[0] : forms[2];
  const a = n % 10;
  const b = n % 100;
  if (a === 1 && b !== 11) return forms[0];
  if (a >= 2 && a <= 4 && (b < 12 || b > 14)) return forms[1];
  return forms[2];
}
